from dataclasses import dataclass
from typing import Optional

__all__ = ["AppAuthAuthorizationResult"]


@dataclass
class AppAuthAuthorizationResult:
    """
    Result of a native AppAuth authorization request (code flow, no token exchange).
    """

    authorization_code: Optional[str] = None
    """
    Authorization code returned by the identity provider, if successful.
    """

    code_verifier: Optional[str] = None
    """
    PKCE code verifier generated by AppAuth for this authorization session.
    """

    error: Optional[str] = None
    """
    Error code when authorization failed or the user cancelled.
    """

    error_description: Optional[str] = None
    """
    Human-readable error details, when available.
    """
